// =============================================================================
// led.v — Tang Nano 9K オンボード LED 6 個を 0.25 秒ごとに 6bit 2 進カウンタ表示
// =============================================================================
// このファイルは Verilog コーディング作法の学習教材を兼ねている。
// 数学ガール風解説書: docs/03_verilog_lesson_01_lika.md を参照。
// -----------------------------------------------------------------------------
// 守られている作法（本ファイル内で確認できる項目）
//   - ANSI-style ポート宣言: input/output wire をモジュールヘッダに直接書く
//   - 末尾 _n で active low（負論理）を示す命名規則
//   - reg / wire の使い分け: always 駆動は reg、組合せ結線は wire
//   - 非同期リセット: posedge clk or negedge rst_n を感度リストに含める
//   - FF への代入は non-blocking ( <= ) で書く（同時更新セマンティクス）
//   - ビット幅明示: 23'd0, 1'b1, 6'd0
//   - 数値の可読性区切り: 6_749_999
// =============================================================================

module led (
    input  wire       sys_clk,    // 27MHz オンボードクロック
    input  wire       sys_rst_n,  // リセット（S1 ボタン、Low=リセット）
                                  // 末尾 _n は「この信号は active low」の慣習表記
    output wire [5:0] led         // オンボード LED x6（Low=点灯, active low）
);

    // -------------------------------------------------------------------------
    // レジスタ宣言
    // -------------------------------------------------------------------------
    // always @(posedge ...) 文の左辺になる変数は reg 型で宣言する作法。
    // 物理的にはフリップフロップ（FF）の塊として合成される。
    reg [22:0] counter;       // 0.25 秒周期分周用カウンタ（27MHz / 6,750,000 = 0.25 秒）
    reg [5:0]  led_count;     // 6bit 2 進カウンタ（64 状態で 1 周期 = 16 秒）

    // -------------------------------------------------------------------------
    // FF ブロック 1: 周期分周カウンタ
    // -------------------------------------------------------------------------
    // 作法ポイント:
    //   1. 感度リストは posedge sys_clk or negedge sys_rst_n （非同期リセット形）
    //   2. if (!sys_rst_n) を最初に書き、それ以外を else 節で記述する定型
    //   3. FF への代入はすべて non-blocking ( <= )
    always @(posedge sys_clk or negedge sys_rst_n) begin
        if (!sys_rst_n)
            counter <= 23'd0;
        else if (counter < 23'd6_749_999)
            counter <= counter + 1'b1;
        else
            counter <= 23'd0;
    end

    // -------------------------------------------------------------------------
    // FF ブロック 2: 表示カウンタ
    // -------------------------------------------------------------------------
    // counter が満了した tick（6,749,999）のときだけ +1。
    // 「else 節を書かない = 暗黙的に値を保持する」のは Verilog の標準挙動。
    always @(posedge sys_clk or negedge sys_rst_n) begin
        if (!sys_rst_n)
            led_count <= 6'd0;
        else if (counter == 23'd6_749_999)
            led_count <= led_count + 1'b1;
    end

    // -------------------------------------------------------------------------
    // 組合せ論理: active low 反転
    // -------------------------------------------------------------------------
    // 単純な組合せ論理は assign 文で書くのが作法（always @(*) でも書けるが冗長）。
    // ハードウェア視点では led_count[i] の各ビットに NOT ゲートを置いた回路に等しい。
    assign led = ~led_count;

endmodule
